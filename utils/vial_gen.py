#!/usr/bin/env python3
"""Emit the C data the Vial protocol serves for one keyboard.

Usage: vial_gen.py VIAL_JSON UID UNLOCK_KEYS

  VIAL_JSON    the Vial keyboard definition (layout, matrix size, name)
  UID          the 8-byte keyboard id as 16 hex digits (0x prefix allowed)
  UNLOCK_KEYS  the keys to hold to unlock, as "row,col;row,col"

The definition is the JSON minified and LZMA-compressed, which is what the Vial GUI expects
and what vial-qmk's own generator produces; it is served in 32-byte pages.
"""

import json
import lzma
import sys


def c_bytes(data):
    return ", ".join("0x{:02X}".format(b) for b in data)


def main():
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 1

    json_path, uid_text, unlock_text = sys.argv[1:]

    with open(json_path, "r") as f:
        definition = json.dumps(json.load(f), separators=(",", ":")).strip()
    compressed = lzma.compress(definition.encode("utf-8"))

    uid = bytes.fromhex(uid_text.removeprefix("0x").removeprefix("0X"))
    if len(uid) != 8:
        print("vial_gen: the keyboard id must be 8 bytes", file=sys.stderr)
        return 1

    keys = [tuple(int(n) for n in pair.split(",")) for pair in unlock_text.split(";") if pair.strip()]
    if not 1 <= len(keys) <= 14:
        print("vial_gen: between 1 and 14 unlock keys are needed", file=sys.stderr)
        return 1

    out = []
    out.append("// Generated by utils/vial_gen.py from {} - do not edit.".format(json_path.replace("\\", "/").split("/")[-1]))
    out.append('#include "vial.h"')
    out.append("")
    out.append("const __code uint8_t vial_definition[] = {{{}}};".format(c_bytes(compressed)))
    out.append("const uint32_t vial_definition_size = {}u;".format(len(compressed)))
    out.append("const __code uint8_t vial_keyboard_uid[8] = {{{}}};".format(c_bytes(uid)))
    out.append("const __code uint8_t vial_unlock_keys[][2] = {{{}}};".format(", ".join("{{{}, {}}}".format(r, c) for r, c in keys)))
    out.append("const uint8_t vial_unlock_key_count = {};".format(len(keys)))
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
